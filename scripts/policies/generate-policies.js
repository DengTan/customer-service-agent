// Extract table names from schema.ts and generate policy files
// Then regenerate the committed snapshot to match scripts/policies/snapshot.ts format.
const fs = require('fs');
const path = require('path');

const schemaPath = path.join(__dirname, '..', '..', 'src', 'storage', 'database', 'shared', 'schema.ts');
const policiesDir = path.join(__dirname, '..', '..', 'supabase', 'policies');

const schema = fs.readFileSync(schemaPath, 'utf8');
const tableMatches = [...schema.matchAll(/export const \w+ = pgTable\(\s*"([a-zA-Z0-9_]+)"/g)];
const tables = tableMatches.map(m => m[1]).sort();

console.log(`Found ${tables.length} tables in schema.ts`);

// NOTE: Files do NOT include a `-- supabase/policies/X.sql` path comment line.
// The snapshot reader (snapshot.ts) reads the full file as-is; the path comment
// was removed to avoid double-nesting in the snapshot BEGIN/END markers.
const policyTemplate = (t) =>
`-- Phase B / B1: explicit service-role pin for ${t}.
-- The application layer connects with service_role (bypasses RLS);
-- these policies are explicit so the snapshot tooling has something
-- to diff against. Tighten to a USING predicate if you ever expose
-- this table to anon/authenticated roles.

DROP POLICY IF EXISTS "${t}_service_role_all" ON public.${t};
CREATE POLICY "${t}_service_role_all"
  ON public.${t}
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);
`;

if (!fs.existsSync(policiesDir)) {
  fs.mkdirSync(policiesDir, { recursive: true });
}

for (const t of tables) {
  fs.writeFileSync(path.join(policiesDir, `${t}.sql`), policyTemplate(t), 'utf8');
  console.log(`  wrote ${t}.sql`);
}

// Regenerate .snapshot.sql — this must match what scripts/policies/snapshot.ts
// reads (full file body, no path-comment stripping).
const files = tables.map(t => `${t}.sql`).sort();
const snapshotBody = files.map(f => {
  const body = fs.readFileSync(path.join(policiesDir, f), 'utf8').trimEnd();
  return `-- >>> BEGIN ${f}\n${body}\n-- <<< END ${f}`;
}).join('\n');

const snapshot = [
  '-- supabase/policies/.snapshot.sql',
  '-- AUTO-GENERATED by scripts/policies/generate-policies.js. Do not edit by hand.',
  `-- File count: ${files.length}`,
  '',
  snapshotBody,
  ''
].join('\n');

fs.writeFileSync(path.join(policiesDir, '.snapshot.sql'), snapshot, 'utf8');
console.log(`\nwrote .snapshot.sql (${tables.length} files)`);

// Write .inventory.json
const inv = { tables, policyFiles: files };
fs.writeFileSync(
  path.join(policiesDir, '.inventory.json'),
  JSON.stringify(inv, null, 2) + '\n',
  'utf8'
);
