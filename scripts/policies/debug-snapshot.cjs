// Debug: compare snapshot files
const fs = require('fs');
const path = require('path');

const snapshotPath = path.join(__dirname, '..', '..', 'supabase', 'policies', '.snapshot.sql');
const content = fs.readFileSync(snapshotPath, 'utf8');
const lines = content.split('\n');
console.log('=== SNAPSHOT FIRST 15 LINES ===');
lines.slice(0, 15).forEach((l, i) => console.log(`${i+1}: ${l}`));

// Now simulate what snapshot.ts would generate
const policiesDir = path.join(__dirname, '..', '..', 'supabase', 'policies');
const files = fs.readdirSync(policiesDir)
  .filter(f => f.endsWith('.sql'))
  .filter(f => f !== '.snapshot.sql')
  .sort();

const snapshotBody = files.map(f => {
  const body = fs.readFileSync(path.join(policiesDir, f), 'utf8').trimEnd();
  return `-- >>> BEGIN ${f}\n${body}\n-- <<< END ${f}`;
}).join('\n');

const header = [
  '-- supabase/policies/.snapshot.sql',
  '-- AUTO-GENERATED by scripts/policies/generate-policies.js. Do not edit by hand.',
  `-- File count: ${files.length}`,
  '',
].join('\n');
const generated = header + '\n' + snapshotBody + '\n';

console.log('\n=== GENERATED FIRST 15 LINES ===');
generated.split('\n').slice(0, 15).forEach((l, i) => console.log(`${i+1}: ${l}`));

console.log('\n=== MATCH?', content === generated);
if (content !== generated) {
  // Find first difference
  for (let i = 0; i < Math.max(content.length, generated.length); i++) {
    if (content[i] !== generated[i]) {
      console.log(`\nFirst diff at char ${i}:`);
      console.log(`  snapshot[${i-20}:${i+20}]: ${JSON.stringify(content.slice(Math.max(0,i-20), i+20))}`);
      console.log(`  generated[${i-20}:${i+20}]: ${JSON.stringify(generated.slice(Math.max(0,i-20), i+20))}`);
      break;
    }
  }
}
